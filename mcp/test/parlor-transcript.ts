import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { randomUUID } from 'node:crypto';
import { createParlorTranscriptHandler, validateTranscriptEvents } from '../src/parlorTranscript';
import { PARLOR_OWNER } from '../src/parlorAccess';
const origin='https://parlor.example.test', secret='synthetic-signing-secret-never-live', providerKey='synthetic-provider-secret-never-live';
let now=Date.now(), revoked=false, authCalls=0, revokeOnSecond=false;
const lines:string[]=[];
const authenticator={authenticate:async(req:{headers:{cookie?:string}})=>{
  authCalls++; if(revokeOnSecond&&authCalls%2===0)return null;
  if(revoked)return null;
  if(req.headers.cookie==='owner-a'||req.headers.cookie==='owner-b')return {identity:PARLOR_OWNER};
  if(req.headers.cookie==='other')return {identity:{...PARLOR_OWNER,subject:'other'}};
  return null;
}};
const options={enabled:true,origin,authenticator,signingSecrets:[secret],redactSecrets:[providerKey],emit:(line:string)=>lines.push(line),now:()=>now};
let handler=createParlorTranscriptHandler(options);
const server=createServer((req,res)=>void handler(req,res));
await new Promise<void>(resolve=>server.listen(0,'127.0.0.1',resolve));
const base=`http://127.0.0.1:${(server.address() as {port:number}).port}/api/parlor/transcript`;
const call=(data:unknown,cookie='owner-a',method='POST',requestOrigin=origin)=>fetch(base,{method,headers:{cookie,origin:requestOrigin,'content-type':'application/json','x-parlor-owner':PARLOR_OWNER.subject},...(method==='POST'?{body:JSON.stringify(data)}:{})});
const event=(extra:Record<string,unknown>={})=>({kind:'user_input',eventId:randomUUID(),seq:1,at:now,part:0,parts:1,text:'synthetic question',...extra});
try {
  for(const cookie of ['', 'forged','other'])assert.equal((await call({start:true},cookie)).status,cookie==='other'?403:401);
  assert.equal((await call({start:true},'owner-a','POST','https://evil.example')).status,403);
  for(const method of ['GET','HEAD','OPTIONS'])assert.equal((await call({},'owner-a',method)).status,405);
  const start=await call({start:true});assert.equal(start.status,200);assert.equal(start.headers.get('cache-control'),'private, no-store');assert.equal(start.headers.get('vary'),'Cookie');
  const {token}=await start.json();assert.equal(lines.length,0);
  assert.equal((await call({token,events:[event()]},'owner-b')).status,403,'receipt is bound to the session cookie, not just account');
  assert.equal((await call({token:token+'bad',events:[event()]})).status,403);
  assert.equal((await call({token,encounterId:randomUUID(),events:[event()]})).status,400,'caller cannot select another encounter');
  const id=JSON.parse(Buffer.from(token.split('.')[0],'base64url').toString()).id;
  const original=event({text:`${providerKey} ${secret} Bearer abcdefghijklmnopqrst`,model:providerKey});
  assert.equal((await call({token,events:[original]})).status,200);
  const logged=JSON.parse(lines[0]);assert.equal(logged.encounterId,id);assert.equal(logged.marker,'parlor_transcript_v1');assert.equal(logged.evidence,'client_reported_not_proof_of_hearing');
  assert.ok(!lines.join('').includes(providerKey)&&!lines.join('').includes(secret)&&!lines.join('').includes(token)&&!lines.join('').includes('owner-a'));
  assert.match(logged.text,/redacted/);
  assert.equal((await call({token,events:[original]})).status,200);assert.equal(JSON.parse(lines[1]).eventId,logged.eventId,'uncertain retries retain deduplication ID');
  const before=lines.length;
  for(const invalid of [event({audio:'no'}),event({headers:{authorization:'no'}}),event({kind:['user_input']}),event({stage:['card']}),event({text:'x'.repeat(1001)}),event({part:2,parts:1}),event({model:'bad\nmetadata'}),event({kind:'error',text:'raw provider error'})]) assert.equal((await call({token,events:[invalid]})).status,400);
  assert.equal((await call({token,events:Array.from({length:9},()=>event())})).status,400);
  assert.equal((await call({token,events:[event({text:'x'.repeat(18000)})]})).status,413);
  assert.equal(lines.length,before,'invalid batches emit no partial content');
  now+=60_001;authCalls=0;revokeOnSecond=true;assert.equal((await call({token,events:[event()]})).status,403);assert.equal(lines.length,before);revokeOnSecond=false;
  revoked=true;assert.equal((await call({token,events:[event()]})).status,401);revoked=false;
  now+=2*60*60*1000;assert.equal((await call({token,events:[event()]})).status,403);
  handler=createParlorTranscriptHandler(options);
  for(let i=0;i<30;i++)assert.equal((await call({start:true})).status,200);
  assert.equal((await call({start:true})).status,429,'bounded owner burst independent of encounter IDs');
  handler=createParlorTranscriptHandler({...options,enabled:false});assert.equal((await call({start:true})).status,404);
  handler=createParlorTranscriptHandler({...options,signingSecrets:[]});assert.equal((await call({start:true})).status,404);
  handler=createParlorTranscriptHandler({...options,authenticator:undefined});assert.equal((await call({start:true})).status,503);
  assert.throws(()=>validateTranscriptEvents([event(),event({cookies:'private'})],[],now));
  console.log('Parlor transcript: synthetic auth/session binding, revocation, size/field/rate limits, redaction, disabled mode and no read methods passed; no guest data or provider calls.');
} finally { server.closeAllConnections();await new Promise<void>(resolve=>server.close(()=>resolve())); }
